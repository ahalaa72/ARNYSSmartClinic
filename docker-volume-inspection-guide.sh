echo ""
echo "Container: openo-tomcat-dev (open-o service)"
echo "  └─ m2-volume -> /root/.m2 (Maven cache, ~1-2GB)"
echo "  └─ ../workspace -> /workspace (source code, bind mount)"
echo "  └─ db_data -> /db-data (database seed data, bind mount)"
echo ""
echo "Container: openo-mariadb-dev (db service)"
echo "  └─ mariadb-files -> /var/lib/mysql (DATABASE, ~11GB)"
echo ""
